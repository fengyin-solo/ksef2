"""Generate plain compatibility modules for the packages renamed in 1.0."""

import argparse
from pathlib import Path
import subprocess
import sys
from typing import cast


PACKAGE = Path(__file__).resolve().parents[1] / "src" / "ksef2"
ROOTS = {
    "_core": ("core", "ksef2, ksef2.xades or ksef2.raw"),
    "_domain": ("domain", "ksef2.models or ksef2.fa3"),
    "_infra": ("infra", "ksef2.raw, ksef2.raw.mappers or ksef2.renderers"),
    "_endpoints": ("endpoints", "ksef2.raw"),
    "_services": ("services", "ksef2.clients, ksef2.fa3 or ksef2.renderers"),
    "_clients": ("clients", "ksef2.clients"),
    "_config": ("config", "ksef2"),
    "_logging": ("logging", "standard logging or structlog configuration"),
}
REPLACEMENTS = {
    "core.exceptions": "ksef2",
    "core.xades": "ksef2.xades",
    "domain.models.fa3": "ksef2.fa3",
    "domain.models": "ksef2.models",
    "infra.mappers": "ksef2.raw.mappers",
    "infra.schema.api.spec": "ksef2.raw.spec",
    "infra.schema.api.supp": "ksef2.raw.supp",
    "infra.schema.fa3": "ksef2.fa3 for invoice construction; retain this alias for generated XSD classes",
    "services.builders": "ksef2.fa3",
    "services.renderers": "ksef2.renderers",
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check = cast(bool, args.check)
    mismatches: list[Path] = []
    count = 0
    for root, (legacy_root, default_replacement) in ROOTS.items():
        source_root = PACKAGE / root
        sources = sorted(source_root.rglob("*.py"))
        if not source_root.is_dir():
            sources = [source_root.with_suffix(".py")]
        for source in sources:
            relative = source.relative_to(PACKAGE)
            if source_root.is_dir():
                destination = PACKAGE / legacy_root / source.relative_to(source_root)
            else:
                destination = PACKAGE / f"{legacy_root}.py"
            if root == "_clients" and source.name == "__init__.py":
                continue
            canonical = "ksef2." + ".".join(relative.with_suffix("").parts)
            legacy = "ksef2." + ".".join(
                destination.relative_to(PACKAGE).with_suffix("").parts
            )
            is_package = source.name == "__init__.py"
            if is_package:
                canonical = canonical.removesuffix(".__init__")
                legacy = legacy.removesuffix(".__init__")
            replacement = default_replacement
            for prefix, public in REPLACEMENTS.items():
                if legacy == f"ksef2.{prefix}" or legacy.startswith(f"ksef2.{prefix}."):
                    replacement = public
                    break
            content = f'''"""Deprecated compatibility {"package" if is_package else "module"} for ``{canonical}``."""

# Generated by scripts/generate_legacy_imports.py. Do not edit by hand.
import warnings
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from {canonical} import *  # noqa: F403

warnings.warn(
    "`{legacy}` is deprecated and will be removed no earlier than "
    "ksef2 2.0.0; use `{replacement}` instead.",
    DeprecationWarning,
    stacklevel=2,
)
'''
            if is_package:
                content += f'''
from importlib import import_module
from typing import cast

_canonical = import_module("{canonical}")


def __getattr__(name: str) -> object:
    if name == "__all__":
        return cast(object, getattr(_canonical, name, [key for key in vars(_canonical) if not key.startswith("_")]))
    return cast(object, getattr(_canonical, name))
'''
            else:
                content += f'''
import sys
from importlib import import_module

sys.modules[__name__] = import_module("{canonical}")
'''
            formatted = subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "ruff",
                    "format",
                    "--stdin-filename",
                    str(destination),
                    "-",
                ],
                input=content,
                capture_output=True,
                text=True,
                check=True,
            ).stdout
            if check:
                if not destination.is_file() or destination.read_text() != formatted:
                    mismatches.append(destination)
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                _ = destination.write_text(formatted)
            count += 1
    if mismatches:
        print("Stale legacy imports:\n" + "\n".join(str(path) for path in mismatches))
        return 1
    print(f"{'Checked' if check else 'Generated'} {count} compatibility files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
